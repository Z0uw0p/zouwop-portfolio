#!/usr/bin/env node
/**
 * sync-redirects.mjs — generate public/_redirects from the Stripe link map.
 *
 * Every available template with a Stripe Payment Link gets one rule:
 *
 *   /go/<slug> https://buy.stripe.com/... 302
 *
 * The product CTA points at /go/<slug>, so Cloudflare Web Analytics counts the
 * redirect as a buy click. A slug with no Stripe link gets no rule (the button
 * still renders "Available soon"), and an unknown slug 404s because no rule or
 * file matches it.
 *
 * Usage:
 *
 *   npm run sync:redirects            # write public/_redirects
 *   npm run sync:redirects -- --check # compare, write nothing
 *
 * Zero dependencies. Node 22.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const GENERATED_TS = path.join(ROOT, 'src/data/templates.generated.ts');
const OVERRIDES_TS = path.join(ROOT, 'src/data/templates.overrides.ts');
const STRIPE_LINKS = path.join(ROOT, 'src/data/stripe-links.json');
const REDIRECTS = path.join(ROOT, 'public/_redirects');
const HEADER = [
  '# Generated by scripts/sync-redirects.mjs — do not edit by hand.',
  '# /go/<slug> is a tracked purchase click; see docs/analytics.md.',
];

function generatedSlugs(text) {
  const assignment = text.indexOf('=', text.indexOf('generatedTemplates'));
  const start = text.indexOf('[', assignment);
  const end = text.lastIndexOf(']');
  if (assignment < 0 || start < 0 || end < start) {
    throw new Error('cannot read generatedTemplates from src/data/templates.generated.ts');
  }
  const parsed = JSON.parse(text.slice(start, end + 1));
  if (!Array.isArray(parsed)) throw new Error('generatedTemplates is not an array');
  return new Set(parsed.map((entry) => entry.slug));
}

function overrideStatuses(text) {
  const start = text.indexOf('overrides');
  if (start < 0) throw new Error('cannot find `overrides` in src/data/templates.overrides.ts');
  const body = text.slice(start);
  const statuses = new Map();
  // Slugs are quoted except `website`, which is a bare identifier.
  const keyRe = /(?:['"]([a-z0-9][a-z0-9-]+)['"]|([a-z0-9][a-z0-9-]+))\s*:\s*\{/g;
  let match;
  while ((match = keyRe.exec(body)) !== null) {
    const slug = match[1] ?? match[2];
    const open = keyRe.lastIndex - 1;
    const close = body.indexOf('}', open);
    if (close < 0) continue;
    const block = body.slice(open + 1, close);
    statuses.set(
      slug,
      /\bstatus\s*:\s*(['"])available\1/.test(block) ? 'available' : 'coming-soon',
    );
  }
  return statuses;
}

export async function build() {
  const [generatedText, overridesText, linksText] = await Promise.all([
    readFile(GENERATED_TS, 'utf8'),
    readFile(OVERRIDES_TS, 'utf8'),
    readFile(STRIPE_LINKS, 'utf8'),
  ]);

  const slugs = generatedSlugs(generatedText);
  const statuses = overrideStatuses(overridesText);
  const links = JSON.parse(linksText);

  if (typeof links !== 'object' || links === null || Array.isArray(links)) {
    throw new Error('src/data/stripe-links.json must be an object of slug -> URL');
  }

  const errors = [];
  for (const [slug, url] of Object.entries(links)) {
    if (!slugs.has(slug)) {
      errors.push(`stripe-links.json: "${slug}" is not in the generated catalog`);
      continue;
    }
    if (statuses.get(slug) !== 'available') {
      errors.push(`stripe-links.json: "${slug}" is not marked available`);
    }
    if (typeof url !== 'string' || !/^https:\/\//.test(url) || url.includes('...')) {
      errors.push(`stripe-links.json: "${slug}" is not a real https URL`);
    }
  }

  const rules = [...slugs]
    .filter((slug) => statuses.get(slug) === 'available' && links[slug])
    .sort()
    .map((slug) => `/go/${slug} ${links[slug]} 302`);

  const missing = [...slugs]
    .filter((slug) => statuses.get(slug) === 'available' && !links[slug])
    .sort();

  const content = `${[...HEADER, ...rules].join('\n')}\n`;
  return { content, errors, missing, count: rules.length };
}

async function run() {
  const check = process.argv.includes('--check');
  const help = process.argv.includes('--help') || process.argv.includes('-h');

  if (help) {
    console.log('Usage: node scripts/sync-redirects.mjs [--check]');
    return;
  }

  let result;
  try {
    result = await build();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }

  if (result.errors.length > 0) {
    for (const error of result.errors) console.error(error);
    console.error(`\n${result.errors.length} redirect error(s). Nothing written.`);
    process.exit(1);
  }

  for (const slug of result.missing) {
    console.warn(`warning: ${slug} is available but has no Stripe link — no /go rule emitted`);
  }

  if (check) {
    let actual = '';
    try {
      actual = await readFile(REDIRECTS, 'utf8');
    } catch {
      console.error('public/_redirects: missing. Run npm run sync:redirects.');
      process.exit(1);
    }
    if (actual !== result.content) {
      console.error('public/_redirects: drifted. Run npm run sync:redirects.');
      process.exit(1);
    }
    console.log(`Redirects match src/data/stripe-links.json (${result.count} rule(s)).`);
    return;
  }

  await writeFile(REDIRECTS, result.content);
  console.log(`Wrote public/_redirects (${result.count} rule(s)).`);
}

await run();
